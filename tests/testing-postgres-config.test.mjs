import test from 'node:test';
import assert from 'node:assert/strict';
import { testingPostgresConfiguration } from '../scripts/lib/testing-postgres-config.mjs';

test('an initialized cluster with only default comments gets the isolated port', () => {
  const config = testingPostgresConfiguration('# Do not edit this file manually!\n# It will be overwritten by ALTER SYSTEM.\n');
  assert.match(config, /^port = 55440$/m);
  assert.match(config, /^listen_addresses = '127\.0\.0\.1'$/m);
  assert.match(config, /^unix_socket_directories = '\/tmp'$/m);
});

test('old network settings cannot retain port 5432 and unrelated settings survive', () => {
  const config = testingPostgresConfiguration("port = 5432\nlisten_addresses = '*'\nunix_socket_directories = '/elsewhere'\nshared_buffers = '128MB'\nport = 55439\n");
  assert.equal(config.includes('5432'), false);
  assert.equal(config.includes('55439'), false);
  assert.equal((config.match(/^port\s*=/gm) || []).length, 1);
  assert.match(config, /^shared_buffers = '128MB'$/m);
});

test('repeated setup preserves one stable testing configuration', () => {
  const first = testingPostgresConfiguration('');
  assert.equal(testingPostgresConfiguration(first), first);
});
